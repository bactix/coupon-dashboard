export function seedData() {
  if (typeof window === "undefined") return;

  const usersKey = "app-users";
  const businessesKey = "businesses";

  const existingUsers = localStorage.getItem(usersKey);
  const existingBusinesses = localStorage.getItem(businessesKey);

  let parsedUsers = existingUsers ? JSON.parse(existingUsers) : [];
  const parsedBusinesses = existingBusinesses ? JSON.parse(existingBusinesses) : [];

  // Ensure admin user always exists
  const adminExists = Array.isArray(parsedUsers) && parsedUsers.some((u: AppUser) => u.email === "admin@gmail.com");

  if (!adminExists) {
    // Add admin user if missing
    if (!Array.isArray(parsedUsers)) parsedUsers = [];
    parsedUsers.unshift(SEED_USERS[0]);
    localStorage.setItem(usersKey, JSON.stringify(parsedUsers));
  }

  if (!Array.isArray(parsedBusinesses) || parsedBusinesses.length === 0) {
    localStorage.setItem(businessesKey, JSON.stringify(SEED_BUSINESSES));
  }
}
